/**
 * Той самий рядок мовою інтерфейсу.
 *
 * `vars` підставляються в `{ключ}` — і в українському оригіналі, і в
 * перекладі, тож порядок слів у реченні кожна мова тримає свій.
 */
export const uiText = (text, language, vars) => {
  const source = String(text ?? '');
  const translated = resolveProfileLanguage(language) === 'en' ? EN_BY_UK[source] ?? source : source;
  if (!vars) return translated;
  return translated.replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key] ?? '') : match
  ));
};

/** Чи має цей український рядок англійський бік. Потрібно тестам словника. */
export const hasUiTranslation = text => Object.prototype.hasOwnProperty.call(EN_BY_UK, String(text ?? ''));

export default uiText;
