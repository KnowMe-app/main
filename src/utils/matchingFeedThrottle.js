/**
 * Стеля на дозавантаження стрічки matching для не-адміна: дві картки на десять
 * секунд, з видимим відліком у кінці списку.
 *
 * Довгий скрол інакше витягує з бекенду сторінку за сторінкою рівно з тією
 * швидкістю, з якою читач гортає. Пауза між сторінками робить цю ціну сталою і,
 * головне, чесно її показує: замість «список ніби скінчився» читач бачить, що
 * картки будуть, і коли саме.
 *
 * Адміна це не стосується — для нього стрічка робочий інструмент, і він
 * впирається в її кінець щодня.
 */
export const MATCHING_THROTTLED_LOAD_DELAY_MS = 10000;
export const MATCHING_THROTTLED_LOAD_BATCH = 2;

/**
 * `с.мс` — секунди й три розряди мілісекунд, як на секундомірі.
 *
 * Мілісекунди тут не прикраса: без них десятисекундна пауза виглядає як
 * застиглий екран, а рухомий останній розряд каже, що сторінка жива.
 */
export const formatMatchingCountdown = remainingMs => {
  const safeMs = Math.max(0, Math.round(Number(remainingMs) || 0));
  const seconds = Math.floor(safeMs / 1000);
  return `${seconds}.${String(safeMs % 1000).padStart(3, '0')}`;
};
