/**
 * Стеля на дозавантаження стрічки matching для не-адміна: дві картки на десять
 * секунд, з видимим відліком у кінці списку.
 *
 * Довгий скрол інакше витягує з бекенду сторінку за сторінкою рівно з тією
 * швидкістю, з якою читач гортає. Пауза між сторінками робить цю ціну сталою і,
 * головне, чесно її показує: замість «список ніби скінчився» читач бачить, що
 * картки будуть, і коли саме.
 *
 * Відлік не заводиться сам: його вмикає прокрутка донизу до кінця списку. Тобто
 * одна порція — один жест читача. Без цього стрічка вантажилась би нескінченно,
 * поки вкладка просто відкрита, — а це рівно те навантаження, від якого пауза й
 * мала захистити.
 *
 * Адміна це не стосується — для нього стрічка робочий інструмент, і він
 * впирається в її кінець щодня.
 */
export const MATCHING_THROTTLED_LOAD_DELAY_MS = 10000;
export const MATCHING_THROTTLED_LOAD_BATCH = 2;

/**
 * Скільки разів один цикл відліку може сходити по картки.
 *
 * Порція рахується в тому, що потрапило на екран, а не в тому, що віддало
 * джерело: фільтри показу проріджують сторінку ще раз, тож із двох знайдених
 * могла лишитись одна. Цикл добирає — але не безкінечно, інакше він
 * перетворився б на той самий потік, від якого пауза й захищає.
 */
export const MATCHING_THROTTLED_LOAD_MAX_ATTEMPTS = 3;

/**
 * Крок відліку.
 *
 * Не кадр: щокадрове оновлення робить останні розряди шумом, який миготить, а не
 * відліком. Двадцять рівних кроків на секунду читаються як секундомір і коштують
 * утричі менше.
 */
export const MATCHING_COUNTDOWN_TICK_MS = 50;

/**
 * Показане значення прив'язане до кроку, а не до точного моменту кадру, — саме
 * тому останні розряди йдуть рівно, а не стрибають випадковими числами.
 */
export const quantizeMatchingCountdown = (remainingMs, tickMs = MATCHING_COUNTDOWN_TICK_MS) => {
  const safeMs = Math.max(0, Number(remainingMs) || 0);
  const step = Math.max(1, Number(tickMs) || 1);
  return Math.ceil(safeMs / step) * step;
};

/**
 * `СС.мс` — секунди й три розряди мілісекунд, як на секундоміри.
 *
 * Секунди доповнені нулем навмисне: без цього «10.000» і «9.950» різної
 * довжини, і на переході з десятої секунди на девʼяту весь рядок смикається
 * вбік. Ширину тримає ще й моноширинний шрифт циферблата.
 */
export const formatMatchingCountdown = remainingMs => {
  const safeMs = Math.max(0, Math.round(Number(remainingMs) || 0));
  const seconds = Math.floor(safeMs / 1000);
  return `${String(seconds).padStart(2, '0')}.${String(safeMs % 1000).padStart(3, '0')}`;
};
