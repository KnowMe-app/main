/**
 * «Назад» — це один жест, а не окрема кнопка на кожному екрані.
 *
 * Апаратна кнопка телефона, «назад» браузера і стрілка в шапці мусять вести в
 * одне й те саме місце: доти форма доповнення закривалась кнопкою «Закрити»
 * внизу екрана (яка вела до видачі пошуку), а апаратна кнопка тим часом
 * поверталась на порожній екран майстерні — два жести «назад» з різним
 * наслідком на одному екрані.
 *
 * Тож форма більше не додає власних записів в історію: «назад» просто знімає
 * той запис, яким її відкрили. Коли знімати нічого (сторінку відкрили
 * посиланням або перезавантажили на адресі форми), лишається запасний шлях —
 * явна адреса того екрана, з якого форму відкривають.
 */

// React Router (v6) веде лічильник записів своєї сесії у `window.history.state`.
// Нуль означає «цей запис перший» — попереднього екрана в історії немає, і
// `navigate(-1)` вивів би читача із застосунку.
export const canGoBackInHistory = () => {
  if (typeof window === 'undefined') return false;
  return Number(window.history?.state?.idx || 0) > 0;
};

export const goBackOrTo = (navigate, fallbackPath) => {
  if (typeof navigate !== 'function') return;
  if (canGoBackInHistory()) {
    navigate(-1);
    return;
  }
  if (fallbackPath) navigate(fallbackPath);
};
