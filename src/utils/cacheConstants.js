/**
 * Скільки живе локальний кеш.
 *
 * Шість годин — це один робочий сеанс роботи з анкетами: за нього читач встигає
 * і повторити той самий пошук, і повернутись до тієї самої картки, і кілька
 * разів перебрати фільтри. Кожен із цих кроків раніше означав ті самі читання
 * з бекенду вдруге й утретє, і саме цю ціну TTL і прибирає.
 */
export const CACHE_TTL_MS = 6 * 60 * 60 * 1000;

/**
 * Проєкції стрічки й списки id живуть стільки ж, скільки анкети.
 *
 * Тут довго стояло десять хвилин — з міркування «проєкція дешева, перечитати не
 * шкода». На практиці шкода: сторінка matching читає їх сотнями, і десять
 * хвилин означали, що повернення до тієї самої видачі через півгодини коштує
 * рівно стільки ж, скільки перше. Свіжість, яку це купувало, — це вік, місто й
 * рядок метрик, тобто те, що змінюється не щогодини.
 */
export const MATCHING_PERFORMANCE_CACHE_TTL_MS = CACHE_TTL_MS;

/**
 * Памʼятки живуть стільки ж — шість годин, з порожніми відповідями включно.
 *
 * Тут стояли десять хвилин з міркування «це те, що дописують одне одному
 * просто зараз». Але чату в застосунку немає, а власний запис і так лягає в
 * кеш одразу (`rememberCommentWrite` у писачах `config.js`): старіти може лише
 * памʼятка спільного власника з іншого пристрою. Ціна десяти хвилин була
 * інша — два точкові читання на кожну показану картку щоразу, коли до неї
 * гортали, і переважно вони відповідали «памʼятки немає».
 */
export const MATCHING_COMMENTS_CACHE_TTL_MS = CACHE_TTL_MS;
