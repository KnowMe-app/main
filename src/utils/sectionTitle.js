// Назви розділів анкети в коді несуть емодзі на початку («📷 Фото»), і цей
// рядок — ключ перекладу (`uiText`), тож у словниках він лишається як є.
// Показується ж назва без нього: емодзі були єдиними на екрані значками
// іншого стилю, ніж лінійні значки навігації й кнопок.
export const stripSectionEmoji = title => String(title || '').replace(/^[^\p{L}\p{N}]+/u, '');
