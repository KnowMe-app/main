/**
 * Значення, які людина вводить замість порожнього поля.
 *
 * Своє місце цей набір має тому, що читають його з двох боків: розкладка
 * анкети (`profileLayoutConfig`) і контакти (`contactMethods`). Тримати його в
 * розкладці не вийшло б — контакти вона сама ж і імпортує, і вийшло б коло.
 *
 * «нема» тут з'явилось не просто так: набір знав «немає» і «нет», але не
 * знав найкоротшої форми — і в анкеті стояли рядки «LinkedIn: Нема»,
 * «YouTube: нема», ще й різним регістром, поруч зі значками порожніх каналів.
 *
 * «no» і «ні» сюди не належать: це відповіді «так/ні», які застосунок сам і
 * підставляє (окуляри, освіта). Зробивши їх порожніми, ми стерли б відповідь,
 * а не заглушку.
 */
export const EMPTY_PLACEHOLDER_VALUES = new Set([
  '',
  '-',
  '—',
  'n/a',
  'na',
  'null',
  'undefined',
  'none',
  'нема',
  'немає',
  'нет',
]);

export const isEmptyPlaceholder = value =>
  EMPTY_PLACEHOLDER_VALUES.has(String(value ?? '').trim().toLowerCase());
