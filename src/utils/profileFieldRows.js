/**
 * Порожній рядок під полем анкети — це намір, а не значення.
 *
 * Кнопка «+» у формі відкриває ще один інпут: адмін збирається дописати нову
 * версію поля (новий телефон, нове прізвище). Поки він нічого не набрав,
 * записувати нема чого — і саме це раніше й ставалось. «+» дописував у поле
 * порожній рядок **і одразу зберігав**, тож скаляр `name: 'Эвелина'`
 * перетворювався на масив `['Эвелина', '']` в анкеті від самого лише дотику до
 * кнопки. У базі другого елемента при цьому не було видно взагалі: проєкція
 * картки збирала самі непорожні значення, тож у `matchingCards` лишалось
 * `{0: 'Эвелина'}` — «масив з одного», якого ніхто не заводив.
 *
 * Ціна цього виросла відтоді, як порожня остання версія почала означати
 * «поле стерли» (`getCurrentValue`): недописаний рядок читався б як стирання, і
 * анкета втрачала б імʼя від одного зайвого дотику.
 *
 * Тому новий рядок додається як `undefined` — «версії ще немає». Форма малює
 * порожній інпут (`value || ''`), а до бази така версія не доїжджає: писач
 * знімає `undefined` з масивів (`removeUndefined`), а `null`, у який його
 * перетворює серіалізація кеша, RTDB не зберігає й поготів. Дірка в масиві
 * стиранням не рахується — на ній береться попередня версія.
 */

/** Чи це порожній рядок форми, а не значення. */
export const isEmptyFieldRow = value =>
  value === undefined || value === null || String(value).trim() === '';

/**
 * Додає до поля ще один порожній рядок. Скаляр при цьому стає масивом версій —
 * але тільки у формі: у базу поле піде масивом лише тоді, коли новий рядок
 * справді заповнять.
 */
export const appendEmptyFieldRow = currentValue => (
  Array.isArray(currentValue) && currentValue.length > 0
    ? [...currentValue, undefined]
    : [currentValue, undefined]
);

/** Чи має сенс пропонувати ще один рядок: попередній уже заповнений. */
export const canAppendFieldRow = currentValue => {
  if (!Array.isArray(currentValue)) return !isEmptyFieldRow(currentValue);
  if (currentValue.length === 0) return false;
  return !isEmptyFieldRow(currentValue[currentValue.length - 1]);
};
