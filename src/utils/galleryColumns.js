/**
 * Дві колонки галереї — розкладка за висотою, а не через одну.
 *
 * Плитки в галереї різної висоти: анкета з фото важить утричі більше за анкету
 * без нього, і ще по рядку додають метрики та кнопки. Розкладка «парні ліворуч,
 * непарні праворуч» ділила порівну **кількість**, а не висоту, тож колонки
 * розʼїжджались: одна закінчувалась на середині екрана, а друга тягнулась далі —
 * і низ списку виглядав як стовпчик карток із порожнечею збоку.
 *
 * Тому плитка йде в ту колонку, яка зараз коротша. Висота при цьому не
 * міряється, а оцінюється: справжню знає лише браузер після розкладки, а
 * оцінки досить, щоб колонки трималися поруч. Одиниця оцінки — ширина колонки:
 * обидві колонки однакові завширшки, тож фото 4/5 важить 1.25 ширини, а рядок
 * тексту — приблизно 0.06.
 *
 * CSS-колонки (`column-count: 2`) браузер вирівняв би сам, але вони міняють
 * порядок читання на «спершу вся ліва колонка»: у стрічці, де порядок задає
 * `feedDate`, це означало б, що друга за свіжістю картка стоїть посеред екрана.
 */

/** Пропорція фото плитки — та сама, що в `GalleryPhotoBox`. */
const PHOTO_ASPECT_HEIGHT = 1.25;

const TILE_BASE_HEIGHT = 0.16;
const TEXT_LINE_HEIGHT = 0.06;
const ACTIONS_HEIGHT = 0.12;

/**
 * Груба висота плитки в частках її ширини.
 *
 * Точність тут не потрібна й недосяжна: ім'я може перенестись, локація —
 * обрізатись. Потрібен лише порядок величини, щоб «з фото» не стало в один ряд
 * з «без фото».
 */
export const estimateGalleryTileHeight = ({
  hasPhoto = false,
  textLines = 0,
  hasActions = false,
} = {}) => TILE_BASE_HEIGHT
  + (hasPhoto ? PHOTO_ASPECT_HEIGHT : 0)
  + Math.max(0, textLines) * TEXT_LINE_HEIGHT
  + (hasActions ? ACTIONS_HEIGHT : 0);

/**
 * Розкласти плитки по колонках, тримаючи їх однакової висоти.
 *
 * Порядок усередині колонки зберігається, а при рівних висотах плитка йде в
 * ліву — інакше перша ж пара мінялася б місцями від найменшої зміни оцінки.
 */
export const splitIntoBalancedColumns = (items = [], estimate = () => 1, columnCount = 2) => {
  const columns = Array.from({ length: Math.max(1, columnCount) }, () => []);
  const heights = new Array(columns.length).fill(0);

  (Array.isArray(items) ? items : []).forEach(item => {
    let target = 0;
    for (let index = 1; index < heights.length; index += 1) {
      if (heights[index] < heights[target] - 1e-9) target = index;
    }
    columns[target].push(item);
    heights[target] += Math.max(0, Number(estimate(item)) || 0);
  });

  return columns;
};
