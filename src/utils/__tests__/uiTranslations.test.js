import { hasUiTranslation, uiText } from '../uiTranslations';

/**
 * Англійський бік екранів матчингу.
 *
 * Перемикач мови в меню трьох крапок був, але виконувала його лише картка
 * анкети: форма створення й доповнення, пошук, чіпи фільтрів і «Мій профіль»
 * лишались українськими хай що вибрано. Словник тут — той самий для всіх цих
 * екранів, і ключ у ньому — сам український рядок, тож неперекладене видно
 * одразу: воно лишається українським, а не зникає.
 */
describe('мова екранів матчингу', () => {
  it('віддає український оригінал, поки мова інтерфейсу українська', () => {
    expect(uiText('Доповнення картки', 'uk')).toBe('Доповнення картки');
  });

  it('перекладає той самий рядок, коли мова англійська', () => {
    expect(uiText('Доповнення картки', 'en')).toBe('Enriching a card');
  });

  // Рядок без перекладу лишається собою: одне українське слово серед
  // англійських видно одразу, а порожнє місце на екрані — ні.
  it('лишає як є рядок, якого в словнику немає', () => {
    expect(uiText('Такого рядка в словнику немає', 'en')).toBe('Такого рядка в словнику немає');
    expect(hasUiTranslation('Такого рядка в словнику немає')).toBe(false);
  });

  // Порядок слів у реченні кожна мова тримає свій, тож підставляння йде вже в
  // перекладений рядок, а не склеюється з шматків.
  it('підставляє значення в обидві мови', () => {
    expect(uiText('Фото {index} з {total}', 'uk', { index: 2, total: 5 })).toBe('Фото 2 з 5');
    expect(uiText('Фото {index} з {total}', 'en', { index: 2, total: 5 })).toBe('Photo 2 of 5');
  });

  it('лишає нерозпізнану підстановку на місці, а не робить з неї порожнечу', () => {
    expect(uiText('Фото {index} з {total}', 'uk', { index: 2 })).toBe('Фото 2 з {total}');
  });

  it('порожній рядок лишається порожнім', () => {
    expect(uiText('', 'en')).toBe('');
    expect(uiText(undefined, 'en')).toBe('');
  });
});
