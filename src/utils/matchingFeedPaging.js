/**
 * Сторінка стрічки matching — одна для першого екрана, для кожної наступної
 * порції й для будь-якого читача.
 *
 * Тут стояла пауза для не-адміна: після першого десятка — дві картки на десять
 * секунд, з відліком у кінці списку, і кожна порція вимагала ще й окремого
 * жесту. Берегла вона трафік, якого майже не було: сторінка `matchingCards`
 * важить ~11 КБ, а переглянути двісті сорок донорок коштувало близько
 * двадцяти хвилин самого чекання. Агенція, для якої стрічка й існує,
 * доходила до кінця рідко — і це читалось не як «притишено», а як «застосунок
 * гальмує». Тепер стрічка гортається так само, як у адміна: сентинел у кінці
 * списку просить наступну сторінку, щойно до неї доходить прокрутка.
 *
 * Число одне на всі три входи — стрічку, фільтри й видачу пошуку: усі три — це
 * «перший результат», і різні пороги в них читались би як різна поведінка того
 * самого екрана.
 *
 * Десять, а не двадцять чотири. Двадцять чотири підбиралось під сітку з
 * невеликих плиток, а рядок стрічки тепер — фото на всю ширину, тобто
 * півтора рядка на екран телефона: перша сторінка тягнула шістнадцять
 * екранів наперед. Разом із запасом джерела (утричі) і подвійним вікном
 * пейджера це було 154 картки `matchingCards` (~35 КБ) заради одного екрана.
 * Наступну сторінку сентинел просить заздалегідь (`rootMargin` у `Matching`),
 * тож гортання меншу порцію не помічає.
 */
export const MATCHING_FEED_PAGE_SIZE = 10;

export const MATCHING_FIRST_PAGE_BATCH = MATCHING_FEED_PAGE_SIZE;

/**
 * Версія пагінації стрічки — частина підпису, за яким кеш стрічки впізнає
 * «свій» стан (`buildFeedCacheSignature` у `Matching.jsx`). Піднімається, коли
 * збережений курсор або позначка «дочитано» могли бути записані хибно:
 * інакше старий стан переживає виправлення на весь TTL.
 *
 * 2 — курсор стає на останню взяту картку, а не в кінець сторінки джерела.
 */
export const MATCHING_FEED_PAGING_VERSION = 2;
