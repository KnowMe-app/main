/**
 * Тумблер «показувати стрілки переходу в бекенд» (EXT/STD на `AddNewProfile`).
 *
 * Вмикають його на одній сторінці, а читають на кількох — форма анкети, картка,
 * блок публічних нотаток у стрічці. Поки ключ був приватною константою
 * `AddNewProfile`, друга сторінка мусила повторити той самий рядок, а розійшлись
 * би вони мовчки: тумблер увімкнено, стрілки не зʼявляються, і зламане не видно
 * ніде, крім `localStorage`.
 *
 * Вимкнено за замовчуванням: сторінка редагування анкети лишається чистою, поки
 * стрілки справді не знадобились. А вибір переживає перезавантаження навмисно —
 * адмін вмикає розширений режим на час розбору, а не на один екран.
 */
export const PROFILE_FORM_EXTENDED_MODE_KEY = 'profileFormExtendedMode';

/**
 * `localStorage` може кинути (приватний режим, заборонені куки), і в цьому разі
 * відповідь — «вимкнено», а не падіння сторінки: стрілки це службова зручність.
 */
export const readBackendLinksEnabled = () => {
  try {
    return typeof localStorage !== 'undefined'
      && localStorage.getItem(PROFILE_FORM_EXTENDED_MODE_KEY) === 'true';
  } catch (error) {
    return false;
  }
};
