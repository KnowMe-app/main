/**
 * Що саме «відмінити» мусить прибрати.
 *
 * Кнопки «відмінити» і «повернути» на екрані анкет працюють знімками: беруть
 * попередній стан картки й зберігають його. Але збереження анкети — це
 * `update`, тобто воно вміє лише **записати** те, що в знімку є. Ключ, який
 * зʼявився після знімка (уперше заповнена пошта, telegram, нотатка), у знімку
 * відсутній — і жодної згадки про нього в запис не потрапляло: відміна
 * поверталася до старих значень, а щойно доданого поля не чіпала взагалі.
 * Зовні це виглядало як «кнопка спрацювала наполовину», причому саме на тому
 * полі, яке щойно вводили.
 *
 * Тому різницю рахують тут, а знімати ключ writer'у каже вже звичайний шлях
 * видалення (`deletedKeys` → `null` у payload).
 */

/**
 * Ключі, яких відміна не знімає ніколи.
 *
 * `userId` — адреса картки, `lastAction` писач ставить сам на кожен запис.
 * Фото ж живуть у Storage, а не в анкеті: `photos` — це список посилань, і
 * знести його ключем означало б «загубити» знімки, які ніхто не видаляв.
 * Знімає їх окремий шлях, який і чистить Storage.
 */
export const HISTORY_PROTECTED_KEYS = ['userId', 'lastAction', 'photos', 'photo'];

const isProtected = key => (
  !key
  || key.startsWith('__')
  || HISTORY_PROTECTED_KEYS.includes(key)
);

/**
 * Ключі, які є в поточній картці й відсутні в знімку, до якого повертаємось.
 *
 * Службові позначки застосунку (`__`-префікс) сюди не потрапляють: у базі їх
 * немає, і знімати нема чого.
 */
export const listKeysAddedSince = (snapshot, current) => {
  if (!current || typeof current !== 'object') return [];
  const target = snapshot && typeof snapshot === 'object' ? snapshot : {};

  return Object.keys(current).filter(key => (
    !isProtected(key) && !Object.prototype.hasOwnProperty.call(target, key)
  ));
};

export default listKeysAddedSince;
