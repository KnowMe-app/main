/**
 * Колір ролі — один на всі екрани матчингу.
 *
 * Роль позначається кольором у чотирьох місцях: смужка на лівому краї рядка
 * стрічки, плашка на знімку в рядку й у відкритій картці, дволітерний код там,
 * де знімка немає. Поки таблиця лежала всередині `MatchingHiddenList.styled`,
 * відкрита картка до неї не дотягувалась і малювала свою плашку сірим — той
 * самий запис виглядав кольоровим у списку й безбарвним, щойно його відкрили.
 *
 * Тут лежать самі значення: це дані про ролі, а не стилі, і залежностей від
 * styled-components у них немає — тож файл можна читати з будь-якого боку, не
 * заводячи кільце між двома таблицями стилів.
 */
export const ROLE_STRIPE_COLORS = {
  ed: '#c95b83',
  ag: '#4d86c9',
  ip: '#3f9b8e',
  sm: '#8a5ec2',
  cl: '#4a9bc9',
};

/** Колір ролі або нічого: невідома роль кольору не отримує. */
export const getRoleColor = role => ROLE_STRIPE_COLORS[String(role || '').trim().toLowerCase()] || '';
