import { formatPhoneDisplay } from './ProfileRow';

/**
 * Номер показується суцільним рядком: його читають, диктують і звіряють з
 * іншим номером, і для всіх трьох справ однаковий вигляд важливіший за
 * групування трійками. Пробіли при цьому бували двох походжень — свої, які
 * малював цей код, і чужі, з якими номер лежить у базі, — тож той самий номер
 * виглядав по-різному залежно від того, як його колись зберегли.
 */
describe('номер телефону в контактах', () => {
  it('знімає власні пробіли', () => {
    expect(formatPhoneDisplay('380501112233')).toBe('+380501112233');
  });

  it('знімає й ті пробіли, з якими номер лежить у базі', () => {
    expect(formatPhoneDisplay('+380 50 111 22 33')).toBe('+380501112233');
    expect(formatPhoneDisplay('+38 (050) 111-22-33')).toBe('+380501112233');
  });

  // «+» дописується лише там, де він щось означає: «+0501112233» не набереться.
  it('місцевий запис лишає без «+»', () => {
    expect(formatPhoneDisplay('0501112233')).toBe('0501112233');
  });

  // Те, що ввела людина, — не номер, і різати його на цифри не можна: вийшов би
  // номер, якого ніхто не набирав.
  it('не чіпає значення з текстом усередині', () => {
    expect(formatPhoneDisplay('0501112233 Оксана')).toBe('0501112233 Оксана');
  });

  it('порожнє лишається порожнім', () => {
    expect(formatPhoneDisplay('')).toBe('');
    expect(formatPhoneDisplay(undefined)).toBe('');
  });
});
